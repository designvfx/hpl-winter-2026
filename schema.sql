-- HPL WINTER 2026 database setup for Supabase
create table if not exists public.teams (
  id bigint primary key,
  name text not null,
  short_name text
);
create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null,
  team_id bigint not null references public.teams(id) on delete restrict,
  role text default 'Player',
  jersey_no integer,
  created_at timestamptz not null default now()
);
create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  match_no integer not null unique,
  stage text not null default 'League',
  team_a_id bigint references public.teams(id),
  team_b_id bigint references public.teams(id),
  team_a_score integer,
  team_b_score integer,
  overs text,
  winner_team_id bigint references public.teams(id),
  status text not null default 'upcoming' check(status in ('upcoming','completed')),
  created_at timestamptz not null default now()
);
create table if not exists public.player_match_stats (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  runs integer not null default 0 check(runs>=0),
  balls_faced integer not null default 0 check(balls_faced>=0),
  fours integer not null default 0 check(fours>=0),
  sixes integer not null default 0 check(sixes>=0),
  wickets integer not null default 0 check(wickets>=0),
  bowling_balls integer not null default 0 check(bowling_balls>=0),
  runs_conceded integer not null default 0 check(runs_conceded>=0),
  maidens integer not null default 0 check(maidens>=0),
  catches integer not null default 0 check(catches>=0),
  dismissed boolean not null default false,
  unique(match_id,player_id)
);
-- Public can read the scoreboard. Only signed-in users can change tournament data.
alter table public.teams enable row level security;
alter table public.players enable row level security;
alter table public.matches enable row level security;
alter table public.player_match_stats enable row level security;
do $$ declare t text; begin foreach t in array array['teams','players','matches','player_match_stats'] loop
 execute format('drop policy if exists public_read on public.%I',t);
 execute format('create policy public_read on public.%I for select using (true)',t);
 execute format('drop policy if exists authenticated_write on public.%I',t);
 execute format('create policy authenticated_write on public.%I for all to authenticated using (true) with check (true)',t);
end loop; end $$;
grant select on public.teams,public.players,public.matches,public.player_match_stats to anon,authenticated;
grant insert,update,delete on public.teams,public.players,public.matches,public.player_match_stats to authenticated;
grant usage,select on all sequences in schema public to authenticated;
